@pytest.mark.parametrize("case", OK_CASES, ids=[c[0] for c in OK_CASES])
def test_offset_matches_independent_historical_reference(case):
    _id, (lat, lon), d, t, zone, offsets, is_dst = case
    r = resolve_birth_timezone(lat, lon, d, t)
    assert r.status == "ok"
    assert r.tz_name == zone
    assert r.utc_offset_hours == pytest.approx(offsets[0], abs=1e-6)
    assert r.offsets[0].is_dst is is_dst
    assert r.time_assumed is False


def test_george_stage0_case_is_utc_plus_5_not_the_plus_4_a_person_would_type():
    r = resolve_birth_timezone(*TBILISI, date(1999, 5, 7), time(23, 30))
    assert r.utc_offset_hours == 5.0
    assert r.utc_offset_hours not in (0.0, 4.0)


def test_repeated_clock_time_is_ambiguous_with_both_offsets_never_guessed():
    r = resolve_birth_timezone(*NEW_YORK, date(2023, 11, 5), time(1, 30))
    assert r.status == "ambiguous"
    assert r.utc_offset_hours is None
    assert [o.utc_offset_hours for o in r.offsets] == [-4.0, -5.0]  # daylight reading first
    assert [o.is_dst for o in r.offsets] == [True, False]


